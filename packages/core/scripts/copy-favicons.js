/*
 * Copies token-generated favicons into dist so they ship with the package
 */

import { cp, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ANSI } from "../../../scripts/utils/ansi-colors.js";

// @rivet-iu/tokens renders every graphic token to SVG, PNG and ICO in its own
// tmp directory. Those are build intermediates, so pick out the handful
// consumers actually link to and give them their conventional names.
const FAVICONS = {
	"apple-touch-icon.png": "apple-touch-icon-3x.png",
	"favicon.ico": "favicon.ico",
	"favicon.svg": "favicon-48.svg",
};

const dist = fileURLToPath(new URL("../dist", import.meta.url));
const tokens = dirname(
	fileURLToPath(import.meta.resolve("@rivet-iu/tokens/package.json")),
);
const source = join(tokens, "tmp");

await mkdir(dist, { recursive: true });

for (const [destination, file] of Object.entries(FAVICONS)) {
	try {
		await cp(join(source, file), join(dist, destination));
	} catch (error) {
		if (error.code !== "ENOENT") throw error;

		throw new Error(
			`Could not find ${join(source, file)}.\n` +
				"Favicons are generated by the tokens package, so build it first:\n" +
				"  pnpm --filter @rivet-iu/tokens build",
			{ cause: error },
		);
	}

	console.log(
		`${ANSI.green}+${ANSI.reset} Copied favicon: dist/${destination}`,
	);
}
